"""Веб-сервис со счётчиком посещений.

Что оно делает
    Отвечает на HTTP-запросы на порту 5000:
      GET /        увеличивает счётчик на 1 и возвращает "Visits: N"
      GET /health  возвращает "ok" (нужно Docker-у для проверки, что сервис жив)

Почему счётчик хранится в файле
    Значение лежит в файле /data/counter.txt, а не в памяти программы.
    Папка /data в Docker подключается как volume (том), то есть хранится
    отдельно от контейнера. Благодаря этому счётчик не сбрасывается, когда
    контейнер удаляют и запускают заново. На этом приложении удобно показать,
    зачем вообще нужны тома: без тома счётчик после пересоздания контейнера
    снова начинается с 1.

Как запустить без Docker (для проверки)
    pip install -r requirements.txt
    DATA_DIR=./data python app.py
    затем открыть http://localhost:5000/
"""
import os

# Flask это библиотека для написания веб-сервисов. Она берёт на себя приём
# HTTP-запросов, а нам остаётся написать функции, которые на них отвечают.
from flask import Flask

# Создаём приложение. Имя переменной `app` важно: сервер gunicorn в контейнере
# запускается командой "gunicorn app:app", что значит "файл app.py, объект app".
app = Flask(__name__)

# Где лежит файл счётчика.
# os.environ.get("DATA_DIR", "/data") читает переменную окружения DATA_DIR,
# а если она не задана, берёт "/data". Путь не зашит в код намертво: его можно
# поменять снаружи, не трогая программу. Настройки через переменные окружения
# это стандартный приём для приложений в контейнерах.
DATA_FILE = os.path.join(os.environ.get("DATA_DIR", "/data"), "counter.txt")


def read_counter():
    """Вернуть текущее значение счётчика из файла."""
    try:
        with open(DATA_FILE) as f:
            # f.read() возвращает текст, например "5\n". strip() убирает
            # пробелы и перенос строки, int() превращает текст в число.
            # `or 0` на случай пустого файла: int("") вызвал бы ошибку.
            return int(f.read().strip() or 0)
    except FileNotFoundError:
        # Файла ещё нет: это самый первый запуск. Считаем, что посещений 0.
        return 0


# Декоратор @app.route("/") связывает адрес с функцией: когда кто-то
# открывает http://<адрес>:5000/, Flask вызывает index() и отправляет в ответ
# то, что функция вернула.
@app.route("/")
def index():
    n = read_counter() + 1
    # Создать папку для данных, если её нет. exist_ok=True значит
    # "не считать ошибкой, если папка уже есть".
    os.makedirs(os.path.dirname(DATA_FILE), exist_ok=True)
    # "w" значит открыть на запись, стерев старое содержимое.
    with open(DATA_FILE, "w") as f:
        f.write(str(n))
    return f"Visits: {n}\n"


# Отдельный адрес для проверки состояния. Он ничего не считает и не пишет на
# диск, только подтверждает, что сервис способен отвечать. Docker обращается
# сюда каждые 30 секунд (команда HEALTHCHECK в Dockerfile.good). Если бы
# проверка ходила на "/", она сама накручивала бы счётчик.
@app.route("/health")
def health():
    return "ok\n"


# Этот блок выполняется, только если файл запущен напрямую: `python app.py`.
# Так его запускает плохой Dockerfile. Хороший запускает приложение через
# gunicorn, который импортирует файл как модуль, и сюда выполнение не доходит.
if __name__ == "__main__":
    # host="0.0.0.0" значит принимать соединения с любых сетевых адресов.
    # Значение по умолчанию 127.0.0.1 означает "только с этой же машины".
    # Для контейнера "эта же машина" это сам контейнер, поэтому со 127.0.0.1
    # сервис был бы недоступен снаружи, даже с флагом -p у docker run.
    #
    # app.run() запускает встроенный сервер Flask. Он годится только для
    # отладки: медленный и не умеет корректно завершаться по сигналу.
    app.run(host="0.0.0.0", port=5000)
