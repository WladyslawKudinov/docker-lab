"""Веб-сервис со счётчиком посещений.

Что оно делает
    Отвечает на HTTP-запросы на порту 5000:
      GET  /        увеличивает счётчик на 1 и возвращает "Visits: N"
      GET  /health  возвращает "ok". Сюда обращается Kubernetes, чтобы
                    проверить, что сервис жив и готов принимать запросы
                    (пробы liveness и readiness в k8s/40-app-deployment.yaml)
      POST /reset   сбрасывает счётчик на начальное значение. Работает,
                    только если в заголовке X-Reset-Token передан правильный
                    токен. Токен приходит из Kubernetes Secret.

Откуда приложение берёт настройки
    Все настройки читаются из переменных окружения. Само приложение не знает,
    что работает в Kubernetes: оно просто читает os.environ. А Kubernetes
    заполняет эти переменные при запуске контейнера:
      DATA_DIR       из ConfigMap  (k8s/10-configmap.yaml), папка с файлом
                     счётчика
      COUNTER_START  из ConfigMap, с какого числа начинать после сброса
      RESET_TOKEN    из Secret     (k8s/20-secret.yaml), пароль для /reset
    Обычные настройки хранят в ConfigMap, пароли и ключи в Secret. Разница
    в том, что доступ к Secret в кластере можно ограничить отдельно, и
    Kubernetes не показывает его значения в обычном выводе команд.

Почему счётчик хранится в файле
    Значение лежит в файле /data/counter.txt, а не в памяти программы.
    Папка /data подключена как том (volume) Kubernetes, который хранится
    отдельно от контейнера и пода. Под можно удалить, Kubernetes создаст
    новый, а счётчик продолжит считать с того же числа.

Откуда берётся начальное значение
    Перед запуском приложения в том же поде выполняется init-контейнер.
    Он создаёт /data/counter.txt с числом COUNTER_START, если файла ещё нет.
    Приложение просто читает файл и продолжает счёт.

Как запустить без Docker и Kubernetes (для проверки)
    pip install -r requirements.txt
    DATA_DIR=./data RESET_TOKEN=test python app.py
    затем открыть http://localhost:5000/
"""
import os

# Flask это библиотека для написания веб-сервисов. Она берёт на себя приём
# HTTP-запросов, а нам остаётся написать функции, которые на них отвечают.
# request даёт доступ к данным текущего запроса, например к заголовкам.
from flask import Flask, request

# Создаём приложение. Имя переменной `app` важно: сервер gunicorn в контейнере
# запускается командой "gunicorn app:app", что значит "файл app.py, объект app".
app = Flask(__name__)

# os.environ.get("ИМЯ", "значение") читает переменную окружения, а если её
# нет, берёт значение по умолчанию. Так программа работает и без Kubernetes.
DATA_FILE = os.path.join(os.environ.get("DATA_DIR", "/data"), "counter.txt")
COUNTER_START = int(os.environ.get("COUNTER_START", "0"))
# Токен для сброса. Значения по умолчанию нет намеренно: если Secret не
# подключили, переменная пустая, и сброс просто не работает. Пароль "по
# умолчанию", зашитый в код, был бы известен всем, кто читал код.
RESET_TOKEN = os.environ.get("RESET_TOKEN", "")


def read_counter():
    """Вернуть текущее значение счётчика из файла."""
    try:
        with open(DATA_FILE) as f:
            # f.read() возвращает текст, например "5\n". strip() убирает
            # пробелы и перенос строки, int() превращает текст в число.
            # `or 0` на случай пустого файла: int("") вызвал бы ошибку.
            return int(f.read().strip() or 0)
    except FileNotFoundError:
        # Файла ещё нет: это самый первый запуск. Считаем, что посещений 0.
        return 0


def write_counter(n):
    """Записать значение счётчика в файл."""
    # Создать папку для данных, если её нет. exist_ok=True значит
    # "не считать ошибкой, если папка уже есть".
    os.makedirs(os.path.dirname(DATA_FILE), exist_ok=True)
    # "w" значит открыть на запись, стерев старое содержимое.
    with open(DATA_FILE, "w") as f:
        f.write(str(n))


# Декоратор @app.route("/") связывает адрес с функцией: когда кто-то
# открывает http://<адрес>:5000/, Flask вызывает index() и отправляет в ответ
# то, что функция вернула.
@app.route("/")
def index():
    n = read_counter() + 1
    write_counter(n)
    # os.environ["HOSTNAME"] в Kubernetes содержит имя пода. Выводим его,
    # чтобы в ответе было видно, какой именно под обработал запрос. После
    # удаления пода имя изменится, а счётчик нет: это и показывает, что
    # данные лежат в томе, а не в контейнере.
    return f"Visits: {n} (pod {os.environ.get('HOSTNAME', '?')})\n"


# Отдельный адрес для проверки состояния. Он ничего не считает и не пишет на
# диск, только подтверждает, что сервис способен отвечать. Kubernetes
# обращается сюда каждые несколько секунд. Если бы проверка ходила на "/",
# она сама накручивала бы счётчик.
@app.route("/health")
def health():
    return "ok\n"


# methods=["POST"]: этот адрес принимает только POST-запросы. GET-запросы
# браузер отправляет сам, например при переходе по ссылке. Действие,
# которое меняет данные, не должно срабатывать от случайного перехода.
@app.route("/reset", methods=["POST"])
def reset():
    # request.headers.get читает заголовок запроса. Клиент передаёт токен
    # так:  curl -X POST -H "X-Reset-Token: <токен>" .../reset
    if not RESET_TOKEN or request.headers.get("X-Reset-Token") != RESET_TOKEN:
        # Вторым значением возвращается код ответа HTTP. 403 значит
        # "доступ запрещён".
        return "forbidden\n", 403
    write_counter(COUNTER_START)
    return f"Counter reset to {COUNTER_START}\n"


# Этот блок выполняется, только если файл запущен напрямую: `python app.py`.
# В контейнере приложение запускается через gunicorn, который импортирует
# файл как модуль, и сюда выполнение не доходит.
if __name__ == "__main__":
    # host="0.0.0.0" значит принимать соединения с любых сетевых адресов.
    # Со 127.0.0.1 (значение по умолчанию) сервис был бы доступен только
    # изнутри самого контейнера.
    app.run(host="0.0.0.0", port=5000)
